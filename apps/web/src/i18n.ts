export type Locale = keyof typeof words;
export type Copy = typeof words.en;
export function civilDay(date = new Date()) {
  return (
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000
  );
}
export function clockTime(date = new Date()) {
  return [date.getHours(), date.getMinutes()]
    .map((n) => String(n).padStart(2, "0"))
    .join(":");
}
export function displayDay(day: number, locale: Locale, calendar: string) {
  return new Intl.DateTimeFormat(locale, {
    weekday: "long",
    month: "long",
    day: "numeric",
    calendar,
    timeZone: "UTC",
  }).format(day * 86400000);
}
