CREATE TABLE medora.operations_config (
  singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
  config jsonb NOT NULL
);
INSERT INTO medora.operations_config(config) VALUES ('{"flags":{"promotions":100,"support":100},"notice":null}');
CREATE TABLE medora.operations_tickets (
  id uuid PRIMARY KEY,
  email text NOT NULL,
  at bigint NOT NULL,
  message text NOT NULL,
  diagnostics text NOT NULL,
  reply text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'open' CHECK(status IN ('open','closed'))
);
CREATE INDEX operations_tickets_email ON medora.operations_tickets(email,at DESC);
CREATE TABLE medora.operations_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at bigint NOT NULL,
  actor text NOT NULL,
  action text NOT NULL
);
CREATE TABLE medora.operations_counters (
  day integer NOT NULL, metric text NOT NULL, count bigint NOT NULL,
  PRIMARY KEY(day,metric)
);
CREATE TABLE medora.operations_history (
  sequence bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  relation_name text NOT NULL,
  previous jsonb,
  following jsonb
);
CREATE FUNCTION medora.record_operations_write() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT phase FROM medora.writer_transition WHERE singleton)='rehearsal' THEN
    INSERT INTO medora.operations_history(relation_name,previous,following)
      VALUES(TG_TABLE_NAME,to_jsonb(OLD),to_jsonb(NEW));
  END IF;
  RETURN NULL;
END;
$$;
DO $$
DECLARE relation text;
BEGIN
  FOREACH relation IN ARRAY ARRAY['operations_config','operations_tickets','operations_audit','operations_counters','operations_history'] LOOP
    EXECUTE format('CREATE TRIGGER guard_write BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON medora.%I
      FOR EACH STATEMENT EXECUTE FUNCTION medora.guard_write()',relation);
    IF relation<>'operations_history' THEN
      EXECUTE format('CREATE TRIGGER record_change AFTER INSERT OR UPDATE OR DELETE ON medora.%I
        FOR EACH ROW EXECUTE FUNCTION medora.record_operations_write()',relation);
    END IF;
    EXECUTE format('CREATE TRIGGER note_truncate AFTER TRUNCATE ON medora.%I
      FOR EACH STATEMENT EXECUTE FUNCTION medora.note_unmapped_write()',relation);
  END LOOP;
END;
$$;
